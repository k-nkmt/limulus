# Load Lark only when a parsing export is first accessed.
_LAZY_SYNTAX_EXPORTS: dict[str, str] = {
    "parse_program": "limulus.syntax.program.parse_program",
    "LarkProgramFrontend": "limulus.syntax.program.LarkProgramFrontend",
    "ParserInitializationError": (
        "limulus.syntax.program.ParserInitializationError"
    ),
    "ProgramRegions": "limulus.syntax.program.ProgramRegions",
}


def __getattr__(name: str):
    path = _LAZY_SYNTAX_EXPORTS.get(name)
    if path is None:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    module_name, _, attribute_name = path.rpartition(".")
    value = getattr(importlib.import_module(module_name), attribute_name)
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    return sorted(set(globals()) | set(_LAZY_SYNTAX_EXPORTS))


